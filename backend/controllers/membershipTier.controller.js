/**
 * List all membership tiers
 */
const getAllTiers = aysncHandler(async (req, res) => {
  const tiers = await MembershipTier.find({ isActive: { $ne: false } }).sort({ order: 1, createdAt: 1 }).lean();

  return res.status(200).json(
    onSuccess("Niveles de membresía obtenidos exitosamente", tiers || [])
  );
});

/**
 * Get available categories that have not yet been created
 */
const getAvailableCategories = aysncHandler(async (req, res) => {
  const existingTiers = await MembershipTier.find({ isActive: { $ne: false } }, "category").lean();
  const existingCategories = existingTiers.map((t) => t.category);
  const availableCategories = ALLOWED_CATEGORIES.filter(
    (cat) => !existingCategories.includes(cat)
  );

  return res.status(200).json(
    onSuccess("Categorías disponibles obtenidas", {
      allCategories: ALLOWED_CATEGORIES,
      existingCategories,
      availableCategories,
      isFull: availableCategories.length === 0,
      totalConfigured: existingCategories.length,
      maxAllowed: ALLOWED_CATEGORIES.length,
    })
  );
});

/**
 * Get single membership tier by ID
 */
const getTierById = aysncHandler(async (req, res, next) => {
  const { id } = req.params;
  const tier = await MembershipTier.findById(id).lean();

  if (!tier) {
    return next(new NotFoundException("Nivel de membresía no encontrado"));
  }

  return res.status(200).json(
    onSuccess("Nivel de membresía obtenido", tier)
  );
});

/**
 * Create a new membership tier (Admin only)
 * Enforces strictly ONE tier per category: 'member' | 'active_member' | 'ambassador' | 'elite_ambassador'
 */
const createTier = aysncHandler(async (req, res, next) => {
  const errors = validationResult(req);
  if (!errors.isEmpty()) {
    return next(new BadRequestException(errors.errors[0].msg));
  }

  const { category, name, nameEn, tag, tagEn, subtitle, subtitleEn, icon, color, level1Rate, level2Rate, qualification, qualificationEn, perks, perksEn, order } = req.body;

  if (!category) {
    return next(new BadRequestException("La categoría del nivel es obligatoria"));
  }

  if (!ALLOWED_CATEGORIES.includes(category)) {
    return next(
      new BadRequestException(
        `Categoría inválida: ${category}. Debe ser una de: ${ALLOWED_CATEGORIES.join(", ")}`
      )
    );
  }

  // Check if a tier with this category already exists
  const existing = await MembershipTier.findOne({ category });
  if (existing) {
    return next(
      new BadRequestException(
        `Ya existe un nivel de membresía para la categoría '${category}'. Solo se permite crear UN nivel por cada categoría (member, active member, ambassador, elite ambassador).`
      )
    );
  }

  // Determine max referral level based on category
  let maxReferralLevel = 0;
  if (category === "active_member") maxReferralLevel = 1;
  else if (category === "ambassador" || category === "elite_ambassador") maxReferralLevel = 2;

  // Determine default order
  const orderMap = { member: 1, active_member: 2, ambassador: 3, elite_ambassador: 4 };
  const tierOrder = order !== undefined ? Number(order) : (orderMap[category] || 1);

  const newTier = await MembershipTier.create({
    category,
    name,
    nameEn: nameEn || name,
    tag: tag || "",
    tagEn: tagEn || "",
    subtitle: subtitle || "",
    subtitleEn: subtitleEn || "",
    icon: icon || "Compass",
    color: color || "#AA303E",
    level1Rate: Number(level1Rate) || 0,
    level2Rate: Number(level2Rate) || 0,
    maxReferralLevel,
    qualification: qualification || "",
    qualificationEn: qualificationEn || "",
    perks: Array.isArray(perks) ? perks : [],
    perksEn: Array.isArray(perksEn) ? perksEn : [],
    order: tierOrder,
    isActive: true,
  });

  return res.status(201).json(
    onSuccess("Nivel de membresía creado exitosamente", newTier)
  );
});

/**
 * Update an existing membership tier (Admin only)
 */
const updateTier = aysncHandler(async (req, res, next) => {
  const { id } = req.params;
  const { category, name, nameEn, tag, tagEn, subtitle, subtitleEn, icon, color, level1Rate, level2Rate, qualification, qualificationEn, perks, perksEn, order, isActive } = req.body;

  const currentTier = await MembershipTier.findById(id);
  if (!currentTier) {
    return next(new NotFoundException("Nivel de membresía no encontrado"));
  }

  // If changing category, ensure no other tier uses the new category
  if (category && category !== currentTier.category) {
    if (!ALLOWED_CATEGORIES.includes(category)) {
      return next(
        new BadRequestException(
          `Categoría inválida: ${category}. Debe ser una de: ${ALLOWED_CATEGORIES.join(", ")}`
        )
      );
    }
    const duplicate = await MembershipTier.findOne({ category, _id: { $ne: id } });
    if (duplicate) {
      return next(
        new BadRequestException(
          `Ya existe otro nivel de membresía para la categoría '${category}'. Solo se permite un nivel por categoría.`
        )
      );
    }
    currentTier.category = category;
  }

  if (name !== undefined) currentTier.name = name;
  if (nameEn !== undefined) currentTier.nameEn = nameEn;
  if (tag !== undefined) currentTier.tag = tag;
  if (tagEn !== undefined) currentTier.tagEn = tagEn;
  if (subtitle !== undefined) currentTier.subtitle = subtitle;
  if (subtitleEn !== undefined) currentTier.subtitleEn = subtitleEn;
  if (icon !== undefined) currentTier.icon = icon;
  if (color !== undefined) currentTier.color = color;
  if (level1Rate !== undefined) currentTier.level1Rate = Number(level1Rate);
  if (level2Rate !== undefined) currentTier.level2Rate = Number(level2Rate);
  if (qualification !== undefined) currentTier.qualification = qualification;
  if (qualificationEn !== undefined) currentTier.qualificationEn = qualificationEn;
  if (perks !== undefined) currentTier.perks = Array.isArray(perks) ? perks : [];
  if (perksEn !== undefined) currentTier.perksEn = Array.isArray(perksEn) ? perksEn : [];
  if (order !== undefined) currentTier.order = Number(order);
  if (isActive !== undefined) currentTier.isActive = Boolean(isActive);

  // Recalculate maxReferralLevel
  if (currentTier.category === "member") currentTier.maxReferralLevel = 0;
  else if (currentTier.category === "active_member") currentTier.maxReferralLevel = 1;
  else currentTier.maxReferralLevel = 2;

  await currentTier.save();

  return res.status(200).json(
    onSuccess("Nivel de membresía actualizado exitosamente", currentTier)
  );
});

/**
 * Delete a membership tier (Admin only)
 */
const deleteTier = aysncHandler(async (req, res, next) => {
  const { id } = req.params;
  const tier = await MembershipTier.findByIdAndUpdate(id, { isActive: false }, { new: true });

  if (!tier) {
    return next(new NotFoundException("Nivel de membresía no encontrado"));
  }

  return res.status(200).json(
    onSuccess("Nivel de membresía eliminado exitosamente", { id, category: tier.category })
  );
});

