export const getCountryByCode = (code) => {
  if (!code) return null;
  return COUNTRIES.find((c) => c.code.toUpperCase() === code.toUpperCase()) || null;
};

export const getCountryByName = (name) => {
  if (!name) return null;
  const n = name.trim().toLowerCase();
  return (
    COUNTRIES.find(
      (c) =>
        c.name.toLowerCase() === n ||
        c.nameEn.toLowerCase() === n ||
        c.code.toLowerCase() === n
    ) || null
  );
};

export const getCountryFlag = (nameOrCode) => {
  if (!nameOrCode) return '🌎';
  const country = getCountryByCode(nameOrCode) || getCountryByName(nameOrCode);
  return country?.flag || '🌎';
};
